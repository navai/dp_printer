"""
Code128 / Code39 条码编码器（clean-room 实现，不依赖 LODOP）

Code128 规范要点：
- 每个字符由 6 个条/空宽度组成（Stop 为 7 段），宽度单位为“模块”
- 共 107 个符号（0~106），103/104/105 分别是 StartA/StartB/StartC
- 校验位 = (start值 + Σ(数据值 × 序号)) mod 103，序号从 1 开始
"""
from typing import List, Tuple

